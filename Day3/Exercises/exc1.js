function add(a, b) {
    return a + b;
}

function subtract(a, b) {
    return a - b;
}

function multiply(a, b) {
    return a * b;
}

function divide(a, b) {
    return a / b;
}

console.log("Addition:", add(15, 20));
console.log("Subtraction:", subtract(25, 5));
console.log("Multiplication:", multiply(7, 6));
console.log("Division:", divide(10, 4));